#!/bin/sh
# OFM: generate deploy/.env with random passwords.
# Needs only Docker. Run from the deploy folder, in PowerShell or a Linux shell:
#
#   docker run --rm -v "${PWD}:/work" -w /work alpine:3.22 sh make-env.sh
#
# It never overwrites an existing .env.
set -eu

if [ -e .env ]; then
  echo "deploy/.env already exists - nothing changed."
  echo "Delete it first only if you really want new passwords (existing databases keep the old ones)."
  exit 1
fi

pw() { tr -dc 'A-Za-z0-9' < /dev/urandom | head -c 24; }

umask 077
NODERED_PW=$(pw)
GRAFANA_PW=$(pw)

cat > .env <<EOT
# OFM secrets, generated by make-env.sh on $(date -u +%Y-%m-%d).
# Keep a copy in a password manager. Never commit this file.

# PostgreSQL / TimescaleDB superuser (migrations and administration only)
POSTGRES_USER=ofm_admin
POSTGRES_PASSWORD=$(pw)

# Database roles, created on the first start of an empty database
OFM_RUNTIME_DB_PASSWORD=$(pw)
OFM_CONFIG_DB_PASSWORD=$(pw)
OFM_READER_DB_PASSWORD=$(pw)

# MQTT users, (re)created by the broker container at every start
OFM_MQTT_RUNTIME_PASSWORD=$(pw)
OFM_MQTT_READER_PASSWORD=$(pw)

# Node-RED editor login
NODERED_ADMIN_USER=admin
NODERED_ADMIN_PASSWORD=${NODERED_PW}

# Encrypts credentials stored by Node-RED. Never change it once set.
NODE_RED_CREDENTIAL_SECRET=$(pw)

# Grafana administrator (applied when Grafana starts with an empty volume)
GRAFANA_USER=admin
GRAFANA_PASSWORD=${GRAFANA_PW}
EOT

# On Linux, give the file to the owner of the folder rather than root.
chown "$(stat -c %u:%g .)" .env 2>/dev/null || true

echo "Created deploy/.env with random passwords."
echo
echo "  Node-RED  http://localhost:1880  user: admin  password: ${NODERED_PW}"
echo "  Grafana   http://localhost:3000  user: admin  password: ${GRAFANA_PW}"
echo
echo "All other passwords are in deploy/.env. Save a copy of it in a password manager."
echo "Next: docker compose up -d"
