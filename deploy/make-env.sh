#!/bin/sh
# OFM: create or complete deploy/.env with random passwords.
# Needs only Docker. Run from the deploy folder, in PowerShell or a Linux shell:
#
#   docker run --rm -v "${PWD}:/work" -w /work alpine:3.22 sh make-env.sh
#
# First run: creates .env with every setting.
# Later runs (e.g. after an upgrade): adds only the settings that are missing.
# An existing value is never changed, so running it again is always safe.
set -eu

pw() { tr -dc 'A-Za-z0-9' < /dev/urandom | head -c "${1:-24}"; }

umask 077
created=no
if [ ! -e .env ]; then
  printf '%s\n' "# OFM secrets, generated by make-env.sh on $(date -u +%Y-%m-%d)." \
                "# Keep a copy in a password manager. Never commit this file." > .env
  created=yes
fi

added=""
section_written=no
# add KEY VALUE "comment": appends KEY=VALUE if KEY is not in .env yet.
add() {
  if grep -q "^$1=" .env; then return 0; fi
  if [ "$created" = no ] && [ "$section_written" = no ]; then
    printf '\n%s\n' "# Added by make-env.sh on $(date -u +%Y-%m-%d)" >> .env
    section_written=yes
  fi
  [ -z "${3:-}" ] || printf '\n# %s\n' "$3" >> .env
  printf '%s=%s\n' "$1" "$2" >> .env
  added="$added $1"
}

add POSTGRES_USER              ofm_admin  "PostgreSQL / TimescaleDB superuser (migrations and administration only)"
add POSTGRES_PASSWORD          "$(pw)"
add OFM_RUNTIME_DB_PASSWORD    "$(pw)"    "Database roles; set from this file at every start"
add OFM_CONFIG_DB_PASSWORD     "$(pw)"
add OFM_READER_DB_PASSWORD     "$(pw)"
add OFM_MATHESAR_DB_PASSWORD   "$(pw)"
add OFM_MQTT_RUNTIME_PASSWORD  "$(pw)"    "MQTT users; set from this file at every start"
add OFM_MQTT_READER_PASSWORD   "$(pw)"
add NODERED_ADMIN_USER         admin      "Node-RED editor login"
add NODERED_ADMIN_PASSWORD     "$(pw)"
add NODE_RED_CREDENTIAL_SECRET "$(pw)"    "Encrypts credentials stored by Node-RED. Never change it once set."
add GRAFANA_USER               admin      "Grafana administrator (applied when Grafana starts with an empty volume)"
add GRAFANA_PASSWORD           "$(pw)"
add MATHESAR_ADMIN_USER        admin      "Mathesar model editor: type these on Mathesar's first-visit setup page"
add MATHESAR_ADMIN_PASSWORD    "$(pw)"
add MATHESAR_DB_PASSWORD       "$(pw)"    "Mathesar's own settings database, and its session key"
add MATHESAR_SECRET_KEY        "$(pw 50)"
add COMPOSE_PROFILES           simulator  "Optional services to run. 'simulator' = the OPC UA simulator (development and demos; leave empty at a plant)"

# On Linux, give the file to the owner of the folder rather than root.
chown "$(stat -c %u:%g .)" .env 2>/dev/null || true

value() { grep "^$1=" .env | head -n 1 | cut -d '=' -f 2-; }

if [ "$created" = yes ]; then
  echo "Created deploy/.env with random passwords."
elif [ -n "$added" ]; then
  echo "deploy/.env already existed. Added the missing settings:"
  for k in $added; do echo "  $k"; done
  echo "Existing values were not changed."
else
  echo "deploy/.env is complete - nothing changed."
  exit 0
fi
echo
echo "  Node-RED  http://localhost:1880  user: $(value NODERED_ADMIN_USER)  password: $(value NODERED_ADMIN_PASSWORD)"
echo "  Grafana   http://localhost:3000  user: $(value GRAFANA_USER)  password: $(value GRAFANA_PASSWORD)"
echo "  Mathesar  http://localhost:8080  user: $(value MATHESAR_ADMIN_USER)  password: $(value MATHESAR_ADMIN_PASSWORD)"
echo
echo "All passwords are in deploy/.env. Save a copy of it in a password manager."
echo "Next: docker compose up -d"
